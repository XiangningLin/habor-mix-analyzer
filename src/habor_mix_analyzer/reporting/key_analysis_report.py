def write_paper_stats(study_tables: dict[str, pd.DataFrame], included_benchmarks: list[str], raw_benchmark: pd.DataFrame | None = None) -> None:
    family_summary = study_tables["benchmark_within_family_summary"]
    model_effects = study_tables["benchmark_model_adjusted_effects"]
    agent_effects = study_tables["benchmark_agent_adjusted_effects"]
    agent_lift = study_tables["benchmark_agent_lift_vs_terminus"]
    terminus_by_model = study_tables["terminus_delta_by_model"]
    headroom = study_tables["benchmark_headroom_by_domain"]
    selected_tasks = study_tables["harbormix_selected_tasks"]

    lines = [
        "% Auto-generated by habor-analyze — do not edit manually.",
        "% Re-generate: uv run habor-analyze studies",
        "",
        "% ── General ──",
        _tex_cmd("NumIncludedBenchmarks", str(len(included_benchmarks))),
        _tex_cmd("NumHaborMixTasks", str(len(selected_tasks))),
        _tex_cmd("NumModels", str(len(model_effects))),
        _tex_cmd("NumAgents", str(len(agent_effects))),
        "",
    ]

    # ── Within-family model vs agent ──
    lines.append("% ── Within-family: model vs agent effect ──")
    for _, row in family_summary.iterrows():
        fam = str(row["family"])
        me_mean = float(row["model_effect_mean"])
        ae_mean = float(row["agent_effect_mean"])
        ratio = me_mean / ae_mean if ae_mean > 1e-9 else float("inf")
        wins = int(row["model_wins"])
        total = int(row["total_benchmarks"])
        pct = 100 * wins / total if total > 0 else 0
        lines += [
            _tex_cmd(f"{fam}ModelEffectMean", _fmt(me_mean, 3)),
            _tex_cmd(f"{fam}AgentEffectMean", _fmt(ae_mean, 3)),
            _tex_cmd(f"{fam}ModelAgentRatio", _fmt(ratio, 1)),
            _tex_cmd(f"{fam}ModelWins", str(wins)),
            _tex_cmd(f"{fam}TotalBenchmarks", str(total)),
            _tex_cmd(f"{fam}ModelWinPct", f"{pct:.0f}"),
        ]
    lines.append("")

    # ── Adjusted effects span ──
    lines.append("% ── Adjusted effects ──")
    model_max = float(model_effects["adjusted_mean"].max())
    model_min = float(model_effects["adjusted_mean"].min())
    agent_max = float(agent_effects["adjusted_mean"].max())
    agent_min = float(agent_effects["adjusted_mean"].min())
    lines += [
        _tex_cmd("ModelEffectSpan", _fmt(model_max - model_min, 2)),
        _tex_cmd("AgentEffectSpan", _fmt(agent_max - agent_min, 2)),
        _tex_cmd("TopModel", str(model_effects.iloc[0]["model"])),
        _tex_cmd("TopModelEffect", _fmt(model_max, 2)),
        _tex_cmd("BottomModel", str(model_effects.iloc[-1]["model"])),
        _tex_cmd("BottomModelEffect", _fmt(model_min, 2)),
        _tex_cmd("TopAgent", str(agent_effects.iloc[0]["agent"])),
        _tex_cmd("TopAgentEffect", _fmt(agent_max, 2)),
        _tex_cmd("BottomAgent", str(agent_effects.iloc[-1]["agent"])),
        _tex_cmd("BottomAgentEffect", _fmt(agent_min, 2)),
    ]
    lines.append("")

    # ── Terminus agent lift ──
    lines.append("% ── Agent lift vs terminus-2 ──")
    for _, row in agent_lift.iterrows():
        agent = str(row["agent"]).replace("-", "")
        lines += [
            _tex_cmd(f"{agent}MeanDelta", _fmt(float(row["mean_delta_vs_terminus"]), 3)),
            _tex_cmd(f"{agent}WinRate", _pct(float(row["win_rate_vs_terminus"]))),
        ]
    lines.append("")

    # ── Best terminus deltas by model ──
    lines.append("% ── Terminus delta by model×agent (top pairs) ──")
    for _, row in terminus_by_model.iterrows():
        model_tag = str(row["model"]).replace("-", "").replace(".", "").replace("_", "")
        agent_tag = str(row["agent"]).replace("-", "").replace(".", "").replace("_", "")
        lines += [
            _tex_cmd(f"Terminus{model_tag}{agent_tag}Delta", _fmt(float(row["mean_delta_vs_terminus"]), 3)),
            _tex_cmd(f"Terminus{model_tag}{agent_tag}WinRate", _pct(float(row["win_rate_vs_terminus"]))),
        ]
    lines.append("")

    # ── Agent lift table (raw-score space) ──
    if "mean_base_raw" in terminus_by_model.columns:
        lines.append("% ── Agent lift table (paper, short names) ──")
        for _, row in terminus_by_model.iterrows():
            key = (str(row["model"]), str(row["agent"]))
            short = _MODEL_TABLE_TAGS.get(key)
            if short is None:
                continue
            base_val = float(row["mean_base_raw"])
            delta_val = float(row["mean_delta_raw"])
            lift_val = float(row["positive_lift_raw"])
            lines += [
                _tex_cmd(f"{short}Base", _fmt_nolz(base_val)),
                _tex_cmd(f"{short}Delta", _fmt_delta(delta_val)),
                _tex_cmd(f"{short}Lift", _pct(lift_val)),
            ]
        lines.append("")

    # ── Headroom summary ──
    lines.append("% ── Benchmark headroom ──")
    n_saturated = len(headroom[headroom["best_score"] >= 0.95])
    n_hard = len(headroom[headroom["best_score"] < 0.50])
    mean_best = float(headroom["best_score"].mean())
    lines += [
        _tex_cmd("NumSaturatedBenchmarks", str(n_saturated)),
        _tex_cmd("NumHardBenchmarks", str(n_hard)),
        _tex_cmd("MeanBestScore", _fmt(mean_best, 3)),
    ]
    lines.append("")

    # ── Per-domain headroom stats ──
    lines.append("% ── Per-domain headroom stats ──")
    domain_stats = []
    for domain, grp in headroom.groupby("domain"):
        n_sat = int((grp["best_score"] >= 0.95).sum())
        n_hrd = int((grp["best_score"] < 0.50).sum())
        mean_bs = float(grp["best_score"].mean())
        tag = str(domain).replace(" ", "").replace("&", "And").replace(",", "")
        lines += [
            _tex_cmd(f"Num{tag}Saturated", str(n_sat)),
            _tex_cmd(f"Num{tag}Hard", str(n_hrd)),
            _tex_cmd(f"Num{tag}Benchmarks", str(len(grp))),
            _tex_cmd(f"Mean{tag}BestScore", f"{100 * mean_bs:.0f}"),
        ]
        domain_stats.append((domain, mean_bs, n_sat, n_hrd, len(grp)))
    domain_stats.sort(key=lambda x: x[1])
    ordinals = ["One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten"]
    for rank_idx, (domain, mean_bs, _, _, _) in enumerate(domain_stats[:3]):
        word = ordinals[rank_idx]
        lines += [
            _tex_cmd(f"MostHeadroomDomain{word}", str(domain)),
            _tex_cmd(f"MostHeadroomDomain{word}Score", f"{100 * mean_bs:.0f}"),
        ]

    se = headroom[headroom["domain"] == "Software Engineering"]
    se_hard = se[se["best_score"] < 0.50].sort_values("best_score")
    lines.append("% ── SE hardest benchmarks (sorted by score) ──")
    for i, (_, row) in enumerate(se_hard.iterrows()):
        bname = benchmark_display_name(row["benchmark"])
        word = ordinals[i]
        lines += [
            _tex_cmd(f"SEHardBenchmark{word}", bname),
            _tex_cmd(f"SEHardBenchmark{word}Score", f"{100 * row['best_score']:.0f}"),
        ]
    lines.append("")

    # ── Effective dimensionality ──
    dim_stats = study_tables["benchmark_effective_dimensionality"]
    if not dim_stats.empty:
        d = dim_stats.iloc[0]
        lines.append("% ── Effective dimensionality ──")
        lines += [
            _tex_cmd("ParticipationRatio", _fmt(float(d["participation_ratio"]), 1)),
            _tex_cmd("ComponentsForNinety", str(int(d["n_components_90pct"]))),
            _tex_cmd("ComponentsForNinetyFive", str(int(d["n_components_95pct"]))),
            _tex_cmd("TopOneVariance", _pct(float(d["top1_variance"]))),
            _tex_cmd("TopThreeVariance", _pct(float(d["top3_variance"]))),
        ]
        lines.append("")

    # ── Domain correlation summary ──
    domain_corr = study_tables["benchmark_domain_correlation_summary"]
    within_row = domain_corr[domain_corr["group"] == "within-domain"]
    cross_row = domain_corr[domain_corr["group"] == "cross-domain"]
    if not within_row.empty and not cross_row.empty:
        lines.append("% ── Domain correlation ──")
        lines += [
            _tex_cmd("WithinDomainMedianCorr", _fmt(float(within_row.iloc[0]["median_spearman"]), 2)),
            _tex_cmd("CrossDomainMedianCorr", _fmt(float(cross_row.iloc[0]["median_spearman"]), 2)),
            _tex_cmd("WithinDomainFracAboveSeven", _pct(float(within_row.iloc[0]["frac_above_0.7"]))),
            _tex_cmd("CrossDomainFracAboveSeven", _pct(float(cross_row.iloc[0]["frac_above_0.7"]))),
        ]
        for _, row in domain_corr.iterrows():
            group = str(row["group"])
            if group.startswith("within: "):
                tag = group.replace("within: ", "").replace(" ", "").replace("&", "And").replace(",", "")
                lines.append(_tex_cmd(f"Within{tag}MedianCorr", _fmt(float(row["median_spearman"]), 2)))
        lines.append("")

    # ── Greedy selection summary ──
    greedy = study_tables["benchmark_greedy_selection"]
    if not greedy.empty:
        lines.append("% ── Greedy benchmark selection ──")
        n_below_07 = int((greedy["max_abs_corr_to_selected"] < 0.7).sum())
        lines += [
            _tex_cmd("GreedyBenchmarksBelowSeven", str(n_below_07)),
        ]
        above_07 = greedy[greedy["max_abs_corr_to_selected"] >= 0.7]
        if not above_07.empty:
            first = above_07.iloc[0]
            lines.append(_tex_cmd("GreedyFirstAboveSeven", str(first["benchmark"])))
            lines.append(_tex_cmd("GreedyFirstAboveSevenStep", str(int(first["step"]))))
        lines.append("")

    # ── HaborMix difficulty composition ──
    lines.append("% ── HaborMix difficulty composition ──")
    tiers = selected_tasks["difficulty_tier"].value_counts().to_dict()
    for tier, count in tiers.items():
        tier_tag = str(tier).capitalize().replace(" ", "")
        lines.append(_tex_cmd(f"HaborMix{tier_tag}Tasks", str(count)))
    lines.append("")

    # BenchPress macros are defined in appendix_quantitative_analysis_details.tex
    # (loaded before paper.tex), so they must not be redefined here.

    # ── AIME case study: agent lift by model capability ──
    if raw_benchmark is not None and "aime" in raw_benchmark.columns:
        lines.append("% ── AIME case study ──")
        aime_data = raw_benchmark[["model", "agent", "aime"]].dropna(subset=["aime"])
        case_study_pairs = [
            ("gpt-5.4", "codex", "GptFourCodex"),
            ("gpt-5-mini", "codex", "GptMiniCodex"),
            ("gpt-5-nano", "codex", "GptNanoCodex"),
        ]
        for model, agent, tag in case_study_pairs:
            agent_row = aime_data[(aime_data["model"] == model) & (aime_data["agent"] == agent)]
            base_row = aime_data[(aime_data["model"] == model) & (aime_data["agent"] == BASELINE_AGENT)]
            if not agent_row.empty and not base_row.empty:
                agent_score = float(agent_row.iloc[0]["aime"])
                base_score = float(base_row.iloc[0]["aime"])
                delta_pp = (agent_score - base_score) * 100
                lines += [
                    _tex_cmd(f"Aime{tag}Base", _fmt(base_score, 3)),
                    _tex_cmd(f"Aime{tag}Agent", _fmt(agent_score, 3)),
                    _tex_cmd(f"Aime{tag}DeltaPP", _fmt(delta_pp, 1)),
                ]
        lines.append("")

    # ── Cross-referenced appendix macros (also needed by paper.tex prose) ──
    # These are computed in write_appendix_stats; we duplicate them here so
    # paper.tex compiles independently of appendix include order.
    lines.append("% ── Appendix macros also used in paper.tex ──")
    uniq = study_tables.get("benchmark_uniqueness_filtered")
    if uniq is not None and "benchpress_medape" in uniq.columns:
        uniq_sorted = uniq.sort_values("benchpress_medape")
        uniq_rev = uniq.sort_values("benchpress_medape", ascending=False)
        for i, label in enumerate(["One", "Two", "Three"]):
            if i < len(uniq_sorted):
                r = uniq_sorted.iloc[i]
                lines += [
                    _tex_cmd(f"BenchPressRedundant{label}", benchmark_display_name(str(r["benchmark"]))),
                    _tex_cmd(f"BenchPressRedundant{label}Score", _fmt(float(r["benchpress_medape"]), 1)),
                ]
            if i < len(uniq_rev):
                r = uniq_rev.iloc[i]
                lines += [
                    _tex_cmd(f"BenchPressUnique{label}", benchmark_display_name(str(r["benchmark"]))),
                    _tex_cmd(f"BenchPressUnique{label}Score", _fmt(float(r["benchpress_medape"]), 1)),
                ]

    greedy = study_tables.get("benchmark_greedy_selection")
    if greedy is not None:
        below_07 = int((greedy["max_abs_corr_to_selected"] < 0.7).sum())
        first_above = greedy[greedy["max_abs_corr_to_selected"] >= 0.7]
        lines += [
            _tex_cmd("GreedyBenchmarksBelowSeven", str(below_07)),
            _tex_cmd("GreedyFirstAboveSeven", benchmark_display_name(str(first_above.iloc[0]["benchmark"])) if len(first_above) > 0 else "—"),
            _tex_cmd("GreedyFirstAboveSevenStep", str(int(first_above.iloc[0]["step"])) if len(first_above) > 0 else "—"),
        ]

    # AppNumSystems used by paper.tex BenchPress paragraph
    if raw_benchmark is not None:
        lines.append(_tex_cmd("AppNumSystems", str(len(raw_benchmark))))

    # SVD spectrum macros used by paper.tex BenchPress paragraph
    from ..studies.benchmark_predictability import _is_pct_col, _to_logit
    if raw_benchmark is not None:
        mat_np = raw_benchmark.drop(columns=KEY_COLUMNS, errors="ignore").select_dtypes(include=[np.number]).values
        agents_list = raw_benchmark["agent"].tolist()
        eps = 0.005
        M_logit = mat_np.copy()
        for j in range(M_logit.shape[1]):
            valid = ~np.isnan(mat_np[:, j])
            if valid.any() and _is_pct_col(mat_np[:, j]):
                M_logit[valid, j] = _to_logit(mat_np[valid, j], eps=eps)
        col_mean = np.nanmean(M_logit, axis=0)
        col_std = np.nanstd(M_logit, axis=0)
        col_std[col_std == 0] = 1
        M_z = (M_logit - col_mean) / col_std
        M_z_filled = np.where(np.isnan(M_z), 0.0, M_z)
        terminus_mask = [a == BASELINE_AGENT for a in agents_list]
        M_model_only = M_z_filled[terminus_mask, :]
        _, s_mo, _ = np.linalg.svd(M_model_only, full_matrices=False)
        v_mo = (s_mo ** 2) / (s_mo ** 2).sum()
        _, s_full, _ = np.linalg.svd(M_z_filled, full_matrices=False)
        v_full = (s_full ** 2) / (s_full ** 2).sum()
        lines += [
            _tex_cmd("AppSVDModelOnlyPCOne", _fmt(v_mo[0] * 100, 1)),
            _tex_cmd("AppSVDFullPCTwo", _fmt(v_full[1] * 100, 1)),
        ]
    lines.append("")

    import re
    tex = PAPER_TEX_PATH.read_text()
    stats_block = "\n".join(lines)
    replacement = f"% @@STATS_BEGIN@@ — auto-generated by habor-analyze, do not edit manually\n{stats_block}\n% @@STATS_END@@"
    tex = re.sub(
        r"% @@STATS_BEGIN@@.*?% @@STATS_END@@",
        lambda _: replacement,
        tex,
        flags=re.DOTALL,
    )
    PAPER_TEX_PATH.write_text(tex)


